export const canIdentity = (c: ColumnRow) =>
  INTEGER_TYPES.has(baseTypeName(c.type)) && !c.isArray;

/** `name type [GENERATED …] [NOT NULL] [DEFAULT …] [UNIQUE]`, for CREATE TABLE or ADD COLUMN. */
export function columnDefinition(
  c: ColumnRow,
  schema: string,
  enums: readonly string[],
) {
  const identity = c.identity && canIdentity(c);
  let def = `${ident(c.name.trim())} ${columnTypeSql(c.type, c.isArray, schema, enums)}`;
  if (identity) def += " GENERATED BY DEFAULT AS IDENTITY";
  if (!c.nullable && !c.primaryKey) def += " NOT NULL";
  if (c.defaultValue.trim() && !identity)
    def += ` DEFAULT ${c.defaultValue.trim()}`;
  if (c.unique && !c.primaryKey) def += " UNIQUE";
  return def;
}

export function buildCreateTableSql(
  schema: string,
  name: string,
  comment: string,
  rls: boolean,
  columns: ColumnRow[],
  foreignKeys: ForeignKeyEntry[],
  enums: readonly string[],
) {
  const table = qualified(schema, name);
  const lines = columns.map((c) => `  ${columnDefinition(c, schema, enums)}`);
  const pk = columns
    .filter((c) => c.primaryKey)
    .map((c) => ident(c.name.trim()));
  if (pk.length) lines.push(`  PRIMARY KEY (${pk.join(", ")})`);
  for (const fk of foreignKeys)
    if (!fk.toRemove) lines.push(`  ${foreignKeyClause(fk)}`);
  return [
    `CREATE TABLE ${table} (\n${lines.join(",\n")}\n);`,
    rls && `ALTER TABLE ${table} ENABLE ROW LEVEL SECURITY;`,
    comment.trim() &&
      `COMMENT ON TABLE ${table} IS ${literal(comment.trim())};`,
  ]
    .filter(Boolean)
    .join("\n\n");
}

/** What the form starts with when updating a table. */
export interface TableInitial {
  name: string;
  comment: string;
  rls: boolean;
  columns: ColumnRow[];
  foreignKeys: ForeignKeyEntry[];
}

export function initialFrom(s: TableStructure): TableInitial {
  const columns = s.columns
    .filter((c) => !c.generated)
    .map((c, i): ColumnRow => {
      const isArray = c.dataType.endsWith("[]");
      const uniqueConstraint = uniqueConstraintOn(s.constraints, c.name)?.name;
      const row = {
        name: c.name,
        type: shortType(isArray ? c.dataType.slice(0, -2) : c.dataType),
        defaultValue: c.default ?? "",
        primaryKey: c.isPrimaryKey,
        nullable: c.nullable,
        unique: uniqueConstraint !== undefined,
        identity: c.identity !== null,
        isArray,
      };
      return { key: i, ...row, original: { ...row, uniqueConstraint } };
    });
  return {
    name: s.name,
    comment: s.comment ?? "",
    rls: s.rlsEnabled,
    columns,
    foreignKeys: s.foreignKeys.map(foreignKeyEntry),
  };
}

/** ALTER statements that turn `init` into what the form now holds. */
export function buildUpdateTableSql(
  schema: string,
  init: TableInitial,
  name: string,
  comment: string,
  rls: boolean,
  columns: ColumnRow[],
  foreignKeys: ForeignKeyEntry[],
  enums: readonly string[],
) {
  const out: string[] = [];
  let table = init.name;
  const alter = () => `ALTER TABLE ${qualified(schema, table)}`;
  if (name !== init.name) {
    out.push(`${alter()} RENAME TO ${ident(name)};`);
    table = name;
  }
  if (comment.trim() !== init.comment.trim())
    out.push(
      `COMMENT ON TABLE ${qualified(schema, table)} IS ${comment.trim() ? literal(comment.trim()) : "NULL"};`,
    );
  if (rls !== init.rls)
    out.push(`${alter()} ${rls ? "ENABLE" : "DISABLE"} ROW LEVEL SECURITY;`);

  // Foreign keys still name columns as they were; follow any renames
  const renamed = new Map(
    columns
      .filter((c) => c.original)
      .map((c) => [c.original!.name, c.name.trim()]),
  );
  const fkSql = foreignKeyStatements(
    schema,
    table,
    foreignKeys.map((fk) => ({
      ...fk,
      pairs: fk.pairs.map((p) => ({
        ...p,
        column: renamed.get(p.column) ?? p.column,
      })),
    })),
  );
  out.push(...fkSql.drops);

  const oldPk = init.columns
    .filter((c) => c.primaryKey)
    .map((c) => renamed.get(c.name) ?? c.name);
  const newPk = columns.filter((c) => c.primaryKey).map((c) => c.name.trim());
  const pkChanged = JSON.stringify(oldPk) !== JSON.stringify(newPk);
  if (pkChanged && oldPk.length) out.push(dropPrimaryKeySql(schema, table));

  for (const c of init.columns)
    if (!columns.some((x) => x.original?.name === c.name))
      out.push(`${alter()} DROP COLUMN ${ident(c.name)};`);

  for (const c of columns) {
    const o = c.original;
    if (!o) {
      out.push(
        `${alter()} ADD COLUMN ${columnDefinition({ ...c, primaryKey: false }, schema, enums)};`,
      );
      continue;
    }
    const after = c.name.trim();
    const before = `${o.type}${o.isArray ? "[]" : ""}`;
    const now = `${c.type.trim()}${c.isArray ? "[]" : ""}`;
    // An identity column whose new type can't be one loses the identity first
    const dropIdentity = o.identity && !canIdentity(c);
    if (dropIdentity)
      out.push(
        `${alter()} ALTER COLUMN ${ident(o.name)} DROP IDENTITY IF EXISTS;`,
      );
    out.push(
      ...alterColumn(
        schema,
        table,
        {
          name: o.name,
          type: before,
          nullable: o.nullable,
          defaultValue: o.defaultValue,
        },
        {
          name: after,
          // Unchanged types stay exactly as Postgres printed them
          type:
            now === before
              ? before
              : columnTypeSql(c.type, c.isArray, schema, enums),
          nullable: c.primaryKey ? false : c.nullable,
          defaultValue:
            o.identity && !dropIdentity ? o.defaultValue : c.defaultValue,
        },
      ),
    );
    if (c.unique !== o.unique && !c.primaryKey)
      out.push(
        c.unique
          ? `${alter()} ADD UNIQUE (${ident(after)});`
          : `${alter()} DROP CONSTRAINT ${ident(o.uniqueConstraint!)};`,
      );
  }

  if (pkChanged && newPk.length)
    out.push(`${alter()} ADD PRIMARY KEY (${newPk.map(ident).join(", ")});`);
  out.push(...fkSql.adds);
  return out.join("\n");
}

/** Supabase's "Duplicate table": the same columns, constraints and indexes, optionally its rows. */
export function duplicateTableSql(
  schema: string,
  table: string,
  name: string,
  withRows: boolean,
) {
  const copy = qualified(schema, name);
  const source = qualified(schema, table);
  return [
    `CREATE TABLE ${copy} (LIKE ${source} INCLUDING ALL);`,
    ...(withRows
      ? [
          `INSERT INTO ${copy} OVERRIDING SYSTEM VALUE SELECT * FROM ${source};`,
          // Identity columns continue after the copied rows
          `DO $$ DECLARE r record; m bigint; BEGIN
  FOR r IN SELECT attname FROM pg_attribute WHERE attrelid = ${literal(copy)}::regclass AND attidentity <> '' LOOP
    EXECUTE format('SELECT max(%I) FROM %s', r.attname, ${literal(copy)}) INTO m;
    IF m IS NOT NULL THEN PERFORM setval(pg_get_serial_sequence(${literal(copy)}, r.attname), m); END IF;
  END LOOP;
END $$;`,
        ]
      : []),
  ].join("\n");
}
