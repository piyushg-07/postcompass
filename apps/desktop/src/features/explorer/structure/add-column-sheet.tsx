import {
  Button,
  Dialog,
  DialogClose,
  Input,
  Select,
  SheetContent,
  Switch,
  toast,
} from "@repo/ui";
import { AlertTriangle, ChevronRight } from "lucide-react";
import { type ReactNode, useState } from "react";
import type { ColumnInfo } from "../../../lib/bindings";
import { describeError } from "../../../lib/ipc";
import {
  alterColumn,
  COMMON_TYPES,
  ident,
  isSafeTypeName,
  literal,
  qualified,
} from "../../../lib/sql";
import { useRunSql } from "../explorer-context";
import { SqlBlock } from "../sql/sql-editor";

const CUSTOM = "__custom__";
const BASE_TYPES = COMMON_TYPES.filter((t) => !t.endsWith("[]"));
const INTEGER_TYPES = new Set(["bigint", "integer", "smallint"]);
/** How Postgres prints some types vs. the names in the picker. */
const TYPE_ALIASES: Record<string, string> = {
  "timestamp with time zone": "timestamptz",
  "timestamp without time zone": "timestamp",
  "character varying(255)": "varchar(255)",
  "time without time zone": "time",
};

/** Handy defaults per type, shown as one-click suggestions. */
const DEFAULT_SUGGESTIONS: Record<string, string[]> = {
  uuid: ["gen_random_uuid()"],
  timestamptz: ["now()"],
  timestamp: ["now()"],
  date: ["current_date"],
  boolean: ["true", "false"],
  jsonb: ["'{}'::jsonb", "'[]'::jsonb"],
  integer: ["0"],
  bigint: ["0"],
  numeric: ["0"],
  text: ["''"],
};

interface Draft {
  name: string;
  comment: string;
  type: string;
  customType: string;
  isArray: boolean;
  defaultValue: string;
  primaryKey: boolean;
  nullable: boolean;
  unique: boolean;
  identity: boolean;
  check: string;
}

function draftFrom(column?: ColumnInfo): Draft {
  if (!column)
    return {
      name: "",
      comment: "",
      type: "text",
      customType: "",
      isArray: false,
      defaultValue: "",
      primaryKey: false,
      nullable: true,
      unique: false,
      identity: false,
      check: "",
    };
  const isArray = column.dataType.endsWith("[]");
  const raw = isArray ? column.dataType.slice(0, -2) : column.dataType;
  const base = TYPE_ALIASES[raw] ?? raw;
  const known = BASE_TYPES.includes(base);
  return {
    name: column.name,
    comment: column.comment ?? "",
    type: known ? base : CUSTOM,
    customType: known ? "" : base,
    isArray,
    defaultValue: column.default ?? "",
    primaryKey: column.isPrimaryKey,
    nullable: column.nullable,
    unique: false,
    identity: column.identity !== null,
    check: "",
  };
}

const typeOf = (d: Draft) =>
  `${d.type === CUSTOM ? d.customType.trim() : d.type}${d.isArray ? "[]" : ""}`;

function addSql(schema: string, table: string, d: Draft) {
  const parts = [
    `ALTER TABLE ${qualified(schema, table)} ADD COLUMN ${ident(d.name.trim())} ${typeOf(d)}`,
  ];
  if (d.identity) parts.push("GENERATED BY DEFAULT AS IDENTITY");
  if (d.primaryKey) parts.push("PRIMARY KEY");
  else if (!d.nullable) parts.push("NOT NULL");
  if (d.defaultValue.trim() && !d.identity)
    parts.push(`DEFAULT ${d.defaultValue.trim()}`);
  if (d.unique && !d.primaryKey) parts.push("UNIQUE");
  if (d.check.trim()) parts.push(`CHECK (${d.check.trim()})`);
  return [`${parts.join(" ")};`];
}

function commentSql(schema: string, table: string, d: Draft) {
  return `COMMENT ON COLUMN ${qualified(schema, table)}.${ident(d.name.trim())} IS ${
    d.comment.trim() ? literal(d.comment.trim()) : "NULL"
  };`;
}

/** Column side panel, laid out like Supabase's: general, data type, constraints. Adds or edits. */
export function ColumnSheet({
  open,
  onOpenChange,
  database,
  schema,
  table,
  column,
}: {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  database: string;
  schema: string;
  table: string;
  /** Present when editing. */
  column?: ColumnInfo | null;
}) {
  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      {open && (
        <ColumnForm
          database={database}
          schema={schema}
          table={table}
          column={column ?? undefined}
          onDone={() => onOpenChange(false)}
        />
      )}
    </Dialog>
  );
}

function ColumnForm({
  database,
  schema,
  table,
  column,
  onDone,
}: {
  database: string;
  schema: string;
  table: string;
  column?: ColumnInfo;
  onDone: () => void;
}) {
  const run = useRunSql();
  const editing = column !== undefined;
  const [initial] = useState(() => draftFrom(column));
  const [d, setD] = useState<Draft>(initial);
  const [showSql, setShowSql] = useState(false);
  const set = <K extends keyof Draft>(key: K, value: Draft[K]) =>
    setD((x) => ({ ...x, [key]: value }));

  const baseType = d.type === CUSTOM ? d.customType.trim() : d.type;
  const canIdentity = !editing && INTEGER_TYPES.has(baseType) && !d.isArray;
  const identity = d.identity && canIdentity;
  const valid =
    d.name.trim().length > 0 &&
    d.name.trim().length <= 63 &&
    baseType.length > 0 &&
    isSafeTypeName(baseType);

  const statements = !valid
    ? []
    : editing
      ? [
          ...alterColumn(
            schema,
            table,
            {
              name: initial.name,
              type: typeOf(initial),
              nullable: initial.nullable,
              defaultValue: initial.defaultValue,
            },
            {
              name: d.name.trim(),
              type: typeOf(d),
              nullable: d.nullable,
              defaultValue: d.defaultValue,
            },
          ),
          ...(d.comment.trim() !== initial.comment.trim()
            ? [commentSql(schema, table, d)]
            : []),
        ]
      : [
          ...addSql(schema, table, { ...d, identity }),
          ...(d.comment.trim() ? [commentSql(schema, table, d)] : []),
        ];
  const sql = statements.join("\n");

  const save = () =>
    sql &&
    run.mutate(
      { sql, database },
      {
        onSuccess: () => {
          toast.success(
            editing
              ? `Column ${d.name.trim()} updated`
              : `Column ${d.name.trim()} added to ${table}`,
          );
          onDone();
        },
      },
    );

  return (
    <SheetContent
      title={
        editing ? (
          <>
            Update column <span className="font-mono">{column.name}</span>
          </>
        ) : (
          <>
            Add new column to <span className="font-mono">{table}</span>
          </>
        )
      }
      className="w-[600px]"
      footer={
        <>
          <DialogClose asChild>
            <Button variant="ghost">Cancel</Button>
          </DialogClose>
          <Button
            variant="primary"
            loading={run.isPending}
            disabled={!sql}
            onClick={save}
          >
            Save
          </Button>
        </>
      }
    >
      <form
        className="flex flex-col gap-6"
        onSubmit={(e) => {
          e.preventDefault();
          save();
        }}
      >
        <Section title="General">
          <Row label="Name" hint="Lowercase names never need quotes in SQL.">
            <Input
              autoFocus
              className="font-mono"
              placeholder="column_name"
              value={d.name}
              onChange={(e) => set("name", e.target.value)}
            />
          </Row>
          <Row
            label="Description"
            hint="Optional. Saved as a comment on the column."
          >
            <Input
              placeholder="What this column holds"
              value={d.comment}
              onChange={(e) => set("comment", e.target.value)}
            />
          </Row>
        </Section>

        <Section title="Data type">
          <Row
            label="Type"
            hint={
              editing
                ? "Existing values are converted to the new type."
                : undefined
            }
          >
            <div className="flex flex-col gap-2">
              <Select
                mono
                value={d.type}
                onValueChange={(type) =>
                  setD((x) => ({
                    ...x,
                    type,
                    defaultValue: editing ? x.defaultValue : "",
                  }))
                }
                options={[
                  ...BASE_TYPES.map((t) => ({ value: t, label: t })),
                  { value: CUSTOM, label: "Other type…" },
                ]}
              />
              {d.type === CUSTOM && (
                <Input
                  className="font-mono"
                  placeholder="e.g. varchar(50), my_enum, numeric(10,2)"
                  value={d.customType}
                  aria-invalid={
                    (d.customType.trim() !== "" &&
                      !isSafeTypeName(d.customType)) ||
                    undefined
                  }
                  onChange={(e) => set("customType", e.target.value)}
                />
              )}
            </div>
          </Row>
          <Toggle
            title="Define as array"
            description="The column holds a list of values, e.g. text[]."
            checked={d.isArray}
            onChange={(v) => set("isArray", v)}
          />
          <Row
            label="Default value"
            hint={
              identity
                ? "Not used for identity columns."
                : "A SQL expression. Leave empty for none."
            }
          >
            <div className="flex flex-col gap-2">
              <Input
                className="font-mono"
                placeholder="NULL"
                disabled={identity}
                value={d.defaultValue}
                onChange={(e) => set("defaultValue", e.target.value)}
              />
              {(DEFAULT_SUGGESTIONS[baseType] ?? []).length > 0 &&
                !identity && (
                  <div className="flex flex-wrap gap-1.5">
                    {DEFAULT_SUGGESTIONS[baseType]!.map((s) => (
                      <button
                        key={s}
                        type="button"
                        onClick={() => set("defaultValue", s)}
                        className="cursor-pointer rounded-control border border-border px-2 py-0.5 font-mono text-[11px] text-fg-muted hover:border-fg-subtle hover:text-fg"
                      >
                        {s}
                      </button>
                    ))}
                  </div>
                )}
            </div>
          </Row>
        </Section>

        <Section title="Constraints">
          {!editing && (
            <Toggle
              title="Is Primary Key"
              description="A primary key uniquely identifies each row. A table can have only one."
              checked={d.primaryKey}
              onChange={(v) => set("primaryKey", v)}
            />
          )}
          {!d.primaryKey && (
            <Toggle
              title="Allow Nullable"
              description="Rows may leave this column empty (NULL)."
              checked={d.nullable}
              onChange={(v) => set("nullable", v)}
            />
          )}
          {!editing && !d.primaryKey && (
            <Toggle
              title="Is Unique"
              description="No two rows can have the same value."
              checked={d.unique}
              onChange={(v) => set("unique", v)}
            />
          )}
          {canIdentity && (
            <Toggle
              title="Is Identity"
              description="Numbers are generated automatically for new rows (1, 2, 3…)."
              checked={d.identity}
              onChange={(v) => set("identity", v)}
            />
          )}
          {!editing && (
            <Row
              label="CHECK constraint"
              hint="Optional. Rows must satisfy it, e.g. price > 0."
            >
              <Input
                className="font-mono"
                placeholder={
                  d.name.trim()
                    ? `length(${ident(d.name.trim())}) < 500`
                    : "value > 0"
                }
                value={d.check}
                onChange={(e) => set("check", e.target.value)}
              />
            </Row>
          )}
          {editing && (
            <p className="text-xs text-fg-subtle">
              Primary key, unique and check constraints are managed in the
              table's Structure view.
            </p>
          )}
        </Section>

        <section className="flex flex-col gap-2">
          <button
            type="button"
            onClick={() => setShowSql((s) => !s)}
            className="flex w-fit cursor-pointer items-center gap-1 text-xs text-fg-muted hover:text-fg"
            aria-expanded={showSql}
          >
            <ChevronRight
              className={`size-3.5 transition-transform ${showSql ? "rotate-90" : ""}`}
            />
            SQL that will run
          </button>
          {showSql && (
            <SqlBlock
              sql={
                sql ||
                (editing
                  ? "-- no changes yet"
                  : "-- give the column a name and type")
              }
              className="max-h-60"
            />
          )}
        </section>

        {run.isError && (
          <div className="flex items-start gap-2 rounded-control border border-danger/30 bg-danger/5 p-2.5 text-xs">
            <AlertTriangle className="mt-0.5 size-3.5 shrink-0 text-danger" />
            <span className="text-fg">{describeError(run.error).message}</span>
          </div>
        )}
        <button type="submit" hidden />
      </form>
    </SheetContent>
  );
}

function Section({ title, children }: { title: string; children: ReactNode }) {
  return (
    <section className="flex flex-col gap-4 border-b border-border pb-6 last-of-type:border-0">
      <h3 className="text-sm font-medium text-fg">{title}</h3>
      {children}
    </section>
  );
}

function Row({
  label,
  hint,
  children,
}: {
  label: string;
  hint?: string;
  children: ReactNode;
}) {
  return (
    <div className="grid grid-cols-[150px_1fr] items-start gap-4">
      <span className="pt-2 text-xs text-fg-muted">{label}</span>
      <div className="flex min-w-0 flex-col gap-1">
        {children}
        {hint && <span className="text-[11px] text-fg-subtle">{hint}</span>}
      </div>
    </div>
  );
}

function Toggle({
  title,
  description,
  checked,
  onChange,
}: {
  title: string;
  description: string;
  checked: boolean;
  onChange: (checked: boolean) => void;
}) {
  return (
    <label className="grid cursor-pointer grid-cols-[150px_1fr] items-start gap-4">
      <span />
      <span className="flex items-start gap-3">
        <Switch
          checked={checked}
          onCheckedChange={onChange}
          className="mt-0.5"
        />
        <span className="flex flex-col gap-0.5">
          <span className="text-sm text-fg">{title}</span>
          <span className="text-xs text-fg-subtle">{description}</span>
        </span>
      </span>
    </label>
  );
}
