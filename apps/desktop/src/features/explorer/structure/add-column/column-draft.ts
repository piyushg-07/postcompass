/** The column panel's form state and the SQL it becomes. Pure, so it can be tested on its own. */
import type { ColumnInfo } from "../../../../lib/bindings";
import { baseTypeName, INTEGER_TYPES, shortType } from "../../../../lib/pg-types";
import {
  alterColumn,
  ident,
  isSafeTypeName,
  literal,
  qualified,
} from "../../../../lib/sql";
import { columnTypeSql, dropPrimaryKeySql } from "../column-sql";
import {
  type ForeignKeyEntry,
  foreignKeyStatements,
} from "../foreign-key-sql";

export interface ColumnDraft {
  name: string;
  comment: string;
  type: string;
  isArray: boolean;
  defaultValue: string;
  primaryKey: boolean;
  nullable: boolean;
  unique: boolean;
  identity: boolean;
  check: string;
}

export const BLANK_COLUMN: ColumnDraft = {
  name: "",
  comment: "",
  type: "",
  isArray: false,
  defaultValue: "",
  primaryKey: false,
  nullable: true,
  unique: false,
  identity: false,
  check: "",
};

/** The type as typed, with `[]` for arrays. */
export const typeOf = (d: ColumnDraft) =>
  `${d.type.trim()}${d.isArray ? "[]" : ""}`;

/** Identity needs an integer type, and can only be chosen for a new column. */
export const canBeIdentity = (d: ColumnDraft) =>
  INTEGER_TYPES.has(baseTypeName(d.type)) && !d.isArray;

/** What the form starts with when editing `column`. */
export function draftFromColumn(column: ColumnInfo): ColumnDraft {
  const isArray = column.dataType.endsWith("[]");
  return {
    ...BLANK_COLUMN,
    name: column.name,
    comment: column.comment ?? "",
    type: shortType(isArray ? column.dataType.slice(0, -2) : column.dataType),
    isArray,
    defaultValue: column.default ?? "",
    primaryKey: column.isPrimaryKey,
    nullable: column.nullable,
    identity: column.identity !== null,
  };
}

export function isDraftValid(d: ColumnDraft) {
  return (
    d.name.trim().length > 0 &&
    d.name.trim().length <= 63 &&
    d.type.trim().length > 0 &&
    isSafeTypeName(d.type)
  );
}

/**
 * An existing identity column keeps its identity unless its new type can't have one; then the
 * identity has to go before the type changes.
 */
export const dropsIdentity = (initial: ColumnDraft, d: ColumnDraft) =>
  initial.identity && !canBeIdentity(d);

/**
 * The statements that add the column (no `existing`) or turn `initial` into `d`. Empty when the
 * form isn't valid or nothing changed.
 */
export function columnSql({
  schema,
  table,
  initial,
  draft: d,
  existing,
  unique,
  uniqueConstraint,
  enums,
  foreignKeys,
}: {
  schema: string;
  table: string;
  initial: ColumnDraft;
  draft: ColumnDraft;
  /** Present when editing. */
  existing?: ColumnInfo;
  /** The unique switch; `null` while untouched. */
  unique: boolean | null;
  /** Name of the column's existing single-column UNIQUE constraint. */
  uniqueConstraint?: string;
  /** Enum names in `schema`, to qualify a picked enum type. */
  enums: readonly string[];
  foreignKeys: ForeignKeyEntry[];
}) {
  if (!isDraftValid(d)) return "";
  const target = qualified(schema, table);
  const colName = d.name.trim();
  const col = ident(colName);
  // Pairs still name the column as it was; point them at its (new) name
  const fkSql = foreignKeyStatements(
    schema,
    table,
    foreignKeys.map((fk) => ({
      ...fk,
      pairs: fk.pairs.map((p) =>
        !p.column || p.column === initial.name ? { ...p, column: colName } : p,
      ),
    })),
  );
  const statements = [...fkSql.drops];

  if (!existing) {
    const identity = d.identity && canBeIdentity(d);
    const isUnique = unique ?? d.unique;
    const parts = [
      `ALTER TABLE ${target} ADD COLUMN ${col} ${columnTypeSql(d.type, d.isArray, schema, enums)}`,
    ];
    if (identity) parts.push("GENERATED BY DEFAULT AS IDENTITY");
    if (d.primaryKey) parts.push("PRIMARY KEY");
    else if (!d.nullable) parts.push("NOT NULL");
    if (d.defaultValue.trim() && !identity)
      parts.push(`DEFAULT ${d.defaultValue.trim()}`);
    if (isUnique && !d.primaryKey) parts.push("UNIQUE");
    if (d.check.trim()) parts.push(`CHECK (${d.check.trim()})`);
    statements.push(`${parts.join(" ")};`);
    if (d.comment.trim())
      statements.push(
        `COMMENT ON COLUMN ${target}.${col} IS ${literal(d.comment.trim())};`,
      );
  } else {
    const typeChanged = typeOf(d) !== typeOf(initial);
    const dropIdentity = dropsIdentity(initial, d);
    if (dropIdentity)
      statements.push(
        `ALTER TABLE ${target} ALTER COLUMN ${ident(initial.name)} DROP IDENTITY IF EXISTS;`,
      );
    statements.push(
      ...alterColumn(
        schema,
        table,
        {
          name: initial.name,
          type: typeOf(initial),
          nullable: initial.nullable,
          defaultValue: initial.defaultValue,
        },
        {
          name: colName,
          // Unchanged types stay exactly as Postgres printed them
          type: typeChanged
            ? columnTypeSql(d.type, d.isArray, schema, enums)
            : typeOf(initial),
          nullable: d.nullable,
          // An identity column can't also have a default
          defaultValue:
            initial.identity && !dropIdentity
              ? initial.defaultValue
              : d.defaultValue,
        },
      ),
    );
    if (d.primaryKey !== initial.primaryKey)
      statements.push(
        d.primaryKey
          ? `ALTER TABLE ${target} ADD PRIMARY KEY (${col});`
          : dropPrimaryKeySql(schema, table),
      );
    if (unique !== null && unique !== (uniqueConstraint !== undefined))
      statements.push(
        unique
          ? `ALTER TABLE ${target} ADD UNIQUE (${col});`
          : `ALTER TABLE ${target} DROP CONSTRAINT ${ident(uniqueConstraint!)};`,
      );
    if (d.check.trim())
      statements.push(`ALTER TABLE ${target} ADD CHECK (${d.check.trim()});`);
    if (d.comment.trim() !== initial.comment.trim())
      statements.push(
        `COMMENT ON COLUMN ${target}.${col} IS ${d.comment.trim() ? literal(d.comment.trim()) : "NULL"};`,
      );
  }
  statements.push(...fkSql.adds);
  return statements.join("\n");
}
