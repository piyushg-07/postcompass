interface ColumnRow {
  key: number;
  name: string;
  type: string;
  defaultValue: string;
  primaryKey: boolean;
  nullable: boolean;
  unique: boolean;
  identity: boolean;
  isArray: boolean;
  /** How an existing column started, when updating a table. */
  original?: Omit<ColumnRow, "key" | "original"> & {
    uniqueConstraint?: string;
  };
}

const blankColumn = (key: number): ColumnRow => ({
  key,
  name: "",
  type: "",
  defaultValue: "",
  primaryKey: false,
  nullable: true,
  unique: false,
  identity: false,
  isArray: false,
});

/** Supabase's starting columns. */
const STARTER: ColumnRow[] = [
  {
    ...blankColumn(0),
    name: "id",
    type: "int8",
    primaryKey: true,
    nullable: false,
    identity: true,
  },
  {
    ...blankColumn(1),
    name: "created_at",
    type: "timestamptz",
    defaultValue: "now()",
    nullable: false,
  },
];

const canIdentity = (c: ColumnRow) =>
  INTEGER_TYPES.has(baseTypeName(c.type)) && !c.isArray;

function buildSql(
  schema: string,
  name: string,
  comment: string,
  rls: boolean,
  columns: ColumnRow[],
  foreignKeys: ForeignKeyEntry[],
) {
  const table = qualified(schema, name);
  const lines = columns.map((c) => {
    let line = `  ${ident(c.name.trim())} ${c.type.trim()}${c.isArray ? "[]" : ""}`;
    const identity = c.identity && canIdentity(c);
    if (identity) line += " GENERATED BY DEFAULT AS IDENTITY";
    if (!c.nullable && !c.primaryKey) line += " NOT NULL";
    if (c.defaultValue.trim() && !identity)
      line += ` DEFAULT ${c.defaultValue.trim()}`;
    if (c.unique && !c.primaryKey) line += " UNIQUE";
    return line;
  });
  const pk = columns
    .filter((c) => c.primaryKey)
    .map((c) => ident(c.name.trim()));
  if (pk.length) lines.push(`  PRIMARY KEY (${pk.join(", ")})`);
  for (const fk of foreignKeys)
    if (!fk.toRemove) lines.push(`  ${foreignKeyClause(fk)}`);
  return [
    `CREATE TABLE ${table} (\n${lines.join(",\n")}\n);`,
    rls && `ALTER TABLE ${table} ENABLE ROW LEVEL SECURITY;`,
    comment.trim() &&
      `COMMENT ON TABLE ${table} IS ${literal(comment.trim())};`,
  ]
    .filter(Boolean)
    .join("\n\n");
}

const columnDefinition = (c: ColumnRow) => {
  const identity = c.identity && canIdentity(c);
  let def = `${ident(c.name.trim())} ${c.type.trim()}${c.isArray ? "[]" : ""}`;
  if (identity) def += " GENERATED BY DEFAULT AS IDENTITY";
  if (!c.nullable && !c.primaryKey) def += " NOT NULL";
  if (c.defaultValue.trim() && !identity)
    def += ` DEFAULT ${c.defaultValue.trim()}`;
  if (c.unique && !c.primaryKey) def += " UNIQUE";
  return def;
};

/** What the form starts with when updating a table. */
interface TableInitial {
  name: string;
  comment: string;
  rls: boolean;
  columns: ColumnRow[];
  foreignKeys: ForeignKeyEntry[];
}

function initialFrom(s: TableStructure): TableInitial {
  const columns = s.columns
    .filter((c) => !c.generated)
    .map((c, i): ColumnRow => {
      const isArray = c.dataType.endsWith("[]");
      const uniqueConstraint = s.constraints.find(
        (k) =>
          k.kind === "unique" &&
          (k.definition === `UNIQUE (${c.name})` ||
            k.definition === `UNIQUE (${ident(c.name)})`),
      )?.name;
      const row = {
        name: c.name,
        type: shortType(isArray ? c.dataType.slice(0, -2) : c.dataType),
        defaultValue: c.default ?? "",
        primaryKey: c.isPrimaryKey,
        nullable: c.nullable,
        unique: uniqueConstraint !== undefined,
        identity: c.identity !== null,
        isArray,
      };
      return { key: i, ...row, original: { ...row, uniqueConstraint } };
    });
  return {
    name: s.name,
    comment: s.comment ?? "",
    rls: s.rlsEnabled,
    columns,
    foreignKeys: s.foreignKeys.map(foreignKeyEntry),
  };
}

/** ALTER statements that turn `init` into what the form now holds. */
function buildUpdateSql(
  schema: string,
  init: TableInitial,
  name: string,
  comment: string,
  rls: boolean,
  columns: ColumnRow[],
  foreignKeys: ForeignKeyEntry[],
) {
  const out: string[] = [];
  let table = init.name;
  const alter = () => `ALTER TABLE ${qualified(schema, table)}`;
  if (name !== init.name) {
    out.push(`${alter()} RENAME TO ${ident(name)};`);
    table = name;
  }
  if (comment.trim() !== init.comment.trim())
    out.push(
      `COMMENT ON TABLE ${qualified(schema, table)} IS ${comment.trim() ? literal(comment.trim()) : "NULL"};`,
    );
  if (rls !== init.rls)
    out.push(`${alter()} ${rls ? "ENABLE" : "DISABLE"} ROW LEVEL SECURITY;`);

  // Foreign keys still name columns as they were; follow any renames
  const renamed = new Map(
    columns
      .filter((c) => c.original)
      .map((c) => [c.original!.name, c.name.trim()]),
  );
  const fkSql = foreignKeyStatements(
    schema,
    table,
    foreignKeys.map((fk) => ({
      ...fk,
      pairs: fk.pairs.map((p) => ({
        ...p,
        column: renamed.get(p.column) ?? p.column,
      })),
    })),
  );
  out.push(...fkSql.drops);

  const oldPk = init.columns
    .filter((c) => c.primaryKey)
    .map((c) => renamed.get(c.name) ?? c.name);
  const newPk = columns.filter((c) => c.primaryKey).map((c) => c.name.trim());
  const pkChanged = JSON.stringify(oldPk) !== JSON.stringify(newPk);
  if (pkChanged && oldPk.length)
    out.push(
      `DO $$ BEGIN EXECUTE format('ALTER TABLE %s DROP CONSTRAINT %I', ${literal(qualified(schema, table))}::regclass, (SELECT conname FROM pg_constraint WHERE conrelid = ${literal(qualified(schema, table))}::regclass AND contype = 'p')); END $$;`,
    );

  for (const c of init.columns)
    if (!columns.some((x) => x.original?.name === c.name))
      out.push(`${alter()} DROP COLUMN ${ident(c.name)};`);

  for (const c of columns) {
    const o = c.original;
    if (!o) {
      out.push(
        `${alter()} ADD COLUMN ${columnDefinition({ ...c, primaryKey: false })};`,
      );
      continue;
    }
    const after = c.name.trim();
    out.push(
      ...alterColumn(
        schema,
        table,
        {
          name: o.name,
          type: `${o.type}${o.isArray ? "[]" : ""}`,
          nullable: o.nullable,
          defaultValue: o.defaultValue,
        },
        {
          name: after,
          type: `${c.type.trim()}${c.isArray ? "[]" : ""}`,
          nullable: c.primaryKey ? false : c.nullable,
          defaultValue: c.identity ? o.defaultValue : c.defaultValue,
        },
      ),
    );
    if (c.unique !== o.unique && !c.primaryKey)
      out.push(
        c.unique
          ? `${alter()} ADD UNIQUE (${ident(after)});`
          : `${alter()} DROP CONSTRAINT ${ident(o.uniqueConstraint!)};`,
      );
  }

  if (pkChanged && newPk.length)
    out.push(`${alter()} ADD PRIMARY KEY (${newPk.map(ident).join(", ")});`);
  out.push(...fkSql.adds);
  return out.join("\n");
}

/** Side panel for creating or updating a table, like Supabase's: name, security, columns, foreign keys. */
export function CreateTableSheet() {
  const { serverId } = useExplorer();
  const target = useCreateTableSheet((s) => s.target);
  const close = useCreateTableSheet((s) => s.close);
  const open = target?.serverId === serverId;

  if (open && target?.mode === "duplicate" && target.table)
    return (
      <DuplicateTableDialog
        key={`${target.database}.${target.schema}.${target.table}`}
        target={{ ...target, table: target.table }}
        onClose={close}
      />
    );
  const editing = target?.mode === "edit" && target.table !== undefined;
  return (
    <Dialog open={open} onOpenChange={(o) => !o && close()}>
      {open &&
        target &&
        (editing ? (
          <UpdateTableLoader
            key={`${target.database}.${target.schema}.${target.table}`}
            target={target}
            onClose={close}
          />
        ) : (
          <TableForm
            key={`${target.database}.${target.schema}`}
            target={target}
            onClose={close}
          />
        ))}
    </Dialog>
  );
}

/** Loads the table's current definition, then shows it in the form. */
function UpdateTableLoader({
  target,
  onClose,
}: {
  target: Target;
  onClose: () => void;
}) {
  const structure = useStructure(target.database, target.schema, target.table!);
  if (!structure.data)
    return (
      <SheetContent title="Update table" className="w-[920px]">
        {structure.isError ? (
          <p className="text-sm text-danger">
            {describeError(structure.error).message}
          </p>
        ) : (
          <div className="flex flex-col gap-2">
            {[0, 1, 2, 3].map((i) => (
              <Skeleton key={i} className="h-9" />
            ))}
          </div>
        )}
      </SheetContent>
    );
  return (
    <TableForm
      target={target}
      initial={initialFrom(structure.data)}
      onClose={onClose}
    />
  );
}

function TableForm({
  target,
  initial,
  onClose,
}: {
  target: Target;
  /** Present when updating an existing table. */
  initial?: TableInitial;
  onClose: () => void;
}) {
  const { database, schema, serverId } = target;
  const run = useRunSql();
  const objects = useSchemaObjects(database, schema);
  const enums = objects.data?.enums ?? [];
  const [name, setName] = useState(initial?.name ?? "");
  const [comment, setComment] = useState(initial?.comment ?? "");
  const [rls, setRls] = useState(initial?.rls ?? true);
  const [columns, setColumns] = useState<ColumnRow[]>(
    initial?.columns ?? STARTER,
  );
  const [nextKey, setNextKey] = useState(
    initial?.columns.length ?? STARTER.length,
  );
  const [foreignKeys, setForeignKeys] = useState<ForeignKeyEntry[]>(
    initial?.foreignKeys ?? [],
  );
  /** Index of the foreign key being edited, or `-1` for a new one (optionally for one column). */
  const [fkEditor, setFkEditor] = useState<{
    index: number;
    column?: string;
  } | null>(null);
  const [dragging, setDragging] = useState<number | null>(null);
  const [showSql, setShowSql] = useState(false);

  const patch = (key: number, p: Partial<ColumnRow>) =>
    setColumns((cs) => cs.map((c) => (c.key === key ? { ...c, ...p } : c)));
  const addColumn = () => {
    setColumns((cs) => [...cs, blankColumn(nextKey)]);
    setNextKey((k) => k + 1);
  };
  const move = (from: number, to: number) =>
    setColumns((cs) => {
      const next = [...cs];
      const [c] = next.splice(from, 1);
      next.splice(to, 0, c!);
      return next;
    });

  const named = columns.filter((c) => c.name.trim());
  const names = named.map((c) => c.name.trim());
  const nameValid = name.trim().length > 0 && name.trim().length <= 63;
  const columnsValid =
    named.length > 0 &&
    new Set(names).size === names.length &&
    named.every((c) => c.type.trim() && isSafeTypeName(c.type));
  const valid = nameValid && columnsValid;
  const primaryKeys = named.filter((c) => c.primaryKey).length;
  const sql = !valid
    ? "-- give the table a name and its columns a name and type"
    : initial
      ? buildUpdateSql(
          schema,
          initial,
          name.trim(),
          comment,
          rls,
          named,
          foreignKeys,
        )
      : buildSql(schema, name.trim(), comment, rls, named, foreignKeys);
  const changed = sql.trim() !== "";

  const submit = () => {
    if (!valid || !changed || run.isPending) return;
    const table = name.trim();
    run.mutate(
      { sql, database },
      {
        onSuccess: () => {
          toast.success(
            initial ? `Table ${table} updated` : `Table ${table} created`,
          );
          onClose();
          const store = useWorkspaceStore.getState();
          // A renamed table's open tabs point at a name that no longer exists
          if (initial && initial.name !== table)
            store.closeTabsFor(
              serverId,
              (t) =>
                t.type === "table" &&
                t.database === database &&
                t.schema === schema &&
                t.name === initial.name,
            );
          if (!initial || initial.name !== table)
            store.openTab(serverId, {
              type: "table",
              database,
              schema,
              name: table,
              kind: "table",
              view: "data",
            });
        },
      },
    );
  };

  return (
    <SheetContent
      title={
        initial ? (
          <>
            Update table <span className="font-mono">{initial.name}</span>
          </>
        ) : (
          <>
            Create a new table under <span className="font-mono">{schema}</span>
          </>
        )
      }
      className="w-[920px]"
      footer={
        <>
          <DialogClose asChild>
            <Button variant="ghost">Cancel</Button>
          </DialogClose>
          <Button
            variant="primary"
            loading={run.isPending}
            disabled={!valid || !changed}
            onClick={submit}
          >
            Save
          </Button>
        </>
      }
    >
      <form
        className="-mx-5 -my-4 flex flex-col divide-y divide-border"
        onSubmit={(e) => {
          e.preventDefault();
          submit();
        }}
        onKeyDown={(e) => {
          if (e.key === "Enter" && (e.ctrlKey || e.metaKey)) submit();
        }}
      >
        <Block>
          <Horizontal label="Name">
            <Input
              autoFocus
              className="font-mono"
              value={name}
              onChange={(e) => setName(e.target.value)}
            />
          </Horizontal>
          <Horizontal label="Description">
            <Input
              placeholder="Optional"
              value={comment}
              onChange={(e) => setComment(e.target.value)}
            />
          </Horizontal>
        </Block>

        <Block>
          <label className="flex cursor-pointer items-start gap-3">
            <Checkbox
              className="mt-0.5"
              checked={rls}
              onCheckedChange={(v) => setRls(v === true)}
            />
            <span className="flex flex-col gap-1">
              <span className="flex items-center gap-2 text-sm text-fg">
                Enable Row Level Security (RLS)
                <Badge>Recommended</Badge>
              </span>
              <span className="text-xs text-fg-muted">
                Restrict access to your table by enabling RLS and writing
                Postgres policies.
              </span>
            </span>
          </label>
          {rls && (
            <Note icon={<Info />}>
              <span className="text-fg">
                Policies are required to query data
              </span>
              <span>
                With RLS on, roles see no rows until a policy allows them. The
                table owner and superusers aren&apos;t affected.
              </span>
            </Note>
          )}
        </Block>

        <Block>
          <h3 className="text-sm text-fg">Columns</h3>
          <div className="flex flex-col gap-2">
            <div className="grid grid-cols-[16px_1fr_1.15fr_1fr_56px_32px_28px] gap-2 text-xs text-fg-muted">
              <span />
              <span>Name</span>
              <span>Type</span>
              <span>Default value</span>
              <span className="text-center">Primary</span>
              <span />
              <span />
            </div>
            {columns.map((c, i) => {
              const enumValues = enums.find((e) => e.name === c.type)?.values;
              const options = [
                !c.nullable,
                c.unique,
                c.identity && canIdentity(c),
                c.isArray,
              ].filter(Boolean).length;
              return (
                <div
                  key={c.key}
                  onDragOver={(e) => {
                    if (dragging === null) return;
                    e.preventDefault();
                    if (dragging !== i) {
                      move(dragging, i);
                      setDragging(i);
                    }
                  }}
                  className={cn(
                    "grid grid-cols-[16px_1fr_1.15fr_1fr_56px_32px_28px] items-center gap-2",
                    dragging === i && "opacity-50",
                  )}
                >
                  <span
                    draggable
                    onDragStart={(e) => {
                      e.dataTransfer.effectAllowed = "move";
                      setDragging(i);
                    }}
                    onDragEnd={() => setDragging(null)}
                    className="flex cursor-grab items-center text-fg-subtle hover:text-fg"
                  >
                    <GripVertical className="size-4" />
                  </span>
                  <div className="relative">
                    <Input
                      aria-label="Column name"
                      className="pr-8 font-mono"
                      placeholder="column_name"
                      spellCheck={false}
                      value={c.name}
                      onChange={(e) => patch(c.key, { name: e.target.value })}
                    />
                    <Tooltip content="Reference a column in another table">
                      <button
                        type="button"
                        aria-label="Reference a column in another table"
                        disabled={!c.name.trim()}
                        onClick={() =>
                          setFkEditor({ index: -1, column: c.name.trim() })
                        }
                        className="absolute top-1/2 right-1.5 flex size-5 -translate-y-1/2 cursor-pointer items-center justify-center rounded text-fg-subtle hover:text-fg disabled:pointer-events-none disabled:opacity-40"
                      >
                        <Link2 className="size-3.5 -rotate-45" />
                      </button>
                    </Tooltip>
                  </div>
                  <TypePicker
                    value={c.type}
                    enums={enums.map((e) => e.name)}
                    onChange={(type) =>
                      patch(c.key, {
                        type,
                        // uuid columns usually want a random default
                        defaultValue:
                          baseTypeName(type) === "uuid" && !c.defaultValue
                            ? "gen_random_uuid()"
                            : c.defaultValue,
                        identity:
                          c.identity && INTEGER_TYPES.has(baseTypeName(type)),
                      })
                    }
                  />
                  <DefaultValueInput
                    value={c.defaultValue}
                    onChange={(v) => patch(c.key, { defaultValue: v })}
                    type={`${c.type}${c.isArray ? "[]" : ""}`}
                    nullable={c.nullable}
                    enumValues={enumValues}
                    disabled={c.identity && canIdentity(c)}
                    placeholder={
                      c.identity && canIdentity(c)
                        ? "Automatically generated"
                        : undefined
                    }
                  />
                  <span className="flex justify-center">
                    <Checkbox
                      aria-label="Primary key"
                      checked={c.primaryKey}
                      onCheckedChange={(v) =>
                        patch(c.key, {
                          primaryKey: v === true,
                          nullable: v === true ? false : c.nullable,
                        })
                      }
                    />
                  </span>
                  <ExtraOptions
                    column={c}
                    count={options}
                    onChange={(p) => patch(c.key, p)}
                  />
                  <button
                    type="button"
                    aria-label="Remove column"
                    onClick={() =>
                      setColumns((cs) => cs.filter((x) => x.key !== c.key))
                    }
                    className="flex size-7 cursor-pointer items-center justify-center rounded text-fg-subtle hover:bg-surface-hover hover:text-fg"
                  >
                    <X className="size-3.5" />
                  </button>
                </div>
              );
            })}
            <button
              type="button"
              onClick={addColumn}
              className="flex h-9 cursor-pointer items-center justify-center gap-1.5 rounded-control border border-dashed border-border-strong text-xs text-fg-muted hover:border-fg-subtle hover:text-fg"
            >
              <Plus className="size-3.5" />
              Add column
            </button>
            {named.length > 0 && primaryKeys === 0 && (
              <Note icon={<AlertTriangle />} warning>
                <span className="text-fg">
                  Warning: No primary keys selected
                </span>
                <span>
                  Rows can only be edited in the table editor when the table has
                  a primary key.
                </span>
              </Note>
            )}
            {primaryKeys > 1 && (
              <Note icon={<Info />}>
                <span className="text-fg">Composite primary key selected</span>
                <span>
                  Each row is identified by the combination of the selected
                  columns.
                </span>
              </Note>
            )}
          </div>
        </Block>

        <Block>
          <h3 className="text-sm text-fg">Foreign keys</h3>
          {foreignKeys.map((fk, i) => (
            <ForeignKeyRow
              key={fk.name ?? `new-${i}`}
              fk={fk}
              onEdit={() => setFkEditor({ index: i })}
              onRemove={() => setForeignKeys((f) => removeForeignKey(f, i))}
              onUndoRemove={() =>
                setForeignKeys((f) => undoRemoveForeignKey(f, i))
              }
            />
          ))}
          <Button
            size="sm"
            variant="secondary"
            className="w-fit"
            iconLeft={<Plus />}
            disabled={named.length === 0}
            onClick={() => setFkEditor({ index: -1 })}
          >
            Add foreign key relation
          </Button>
        </Block>

        <Block>
          <button
            type="button"
            onClick={() => setShowSql((s) => !s)}
            className="w-fit cursor-pointer text-xs text-fg-subtle hover:text-fg"
          >
            {showSql ? "Hide SQL" : "View SQL"}
          </button>
          {showSql && <SqlBlock sql={sql} className="max-h-72" />}
          {run.isError && (
            <div className="flex items-start gap-2 rounded-control border border-danger/30 bg-danger/5 p-2.5 text-xs">
              <AlertTriangle className="mt-0.5 size-3.5 shrink-0 text-danger" />
              <span className="text-fg">
                {describeError(run.error).message}
              </span>
            </div>
          )}
        </Block>
      </form>

      <ForeignKeySheet
        open={fkEditor !== null}
        onOpenChange={(o) => !o && setFkEditor(null)}
        database={database}
        schema={schema}
        table={name.trim()}
        columns={names}
        initial={
          fkEditor && fkEditor.index >= 0
            ? foreignKeys[fkEditor.index]
            : fkEditor?.column
              ? {
                  schema,
                  table: "",
                  pairs: [{ column: fkEditor.column, refColumn: "" }],
                  onUpdate: "NO ACTION",
                  onDelete: "NO ACTION",
                }
              : undefined
        }
        onSave={(fk) =>
          setForeignKeys((list) =>
            saveForeignKey(list, fkEditor?.index ?? -1, fk),
          )
        }
      />
    </SheetContent>
  );
}

/** The gear popover on a column row: Supabase's "Extra options". */
function ExtraOptions({
  column: c,
  count,
  onChange,
}: {
  column: ColumnRow;
  count: number;
  onChange: (p: Partial<ColumnRow>) => void;
}) {
  const option = (
    label: string,
    description: string,
    checked: boolean,
    set: (v: boolean) => void,
    disabled = false,
  ) => (
    <label
      className={cn(
        "flex cursor-pointer items-start gap-2.5",
        disabled && "pointer-events-none opacity-50",
      )}
    >
      <Checkbox
        className="mt-0.5"
        checked={checked}
        disabled={disabled}
        onCheckedChange={(v) => set(v === true)}
      />
      <span className="flex flex-col gap-0.5">
        <span className="text-xs text-fg">{label}</span>
        <span className="text-[11px] text-fg-subtle">{description}</span>
      </span>
    </label>
  );
  return (
    <Popover>
      <Tooltip content="Set column constraints and array options">
        <PopoverTrigger asChild>
          <button
            type="button"
            aria-label="Extra options"
            className="relative flex size-8 cursor-pointer items-center justify-center rounded-control border border-border-strong text-fg-subtle hover:text-fg data-[state=open]:text-fg"
          >
            <Settings2 className="size-3.5" />
            {count > 0 && (
              <span className="absolute -top-1.5 -right-1.5 flex size-4 items-center justify-center rounded-full bg-accent text-[9px] font-medium text-black">
                {count}
              </span>
            )}
          </button>
        </PopoverTrigger>
      </Tooltip>
      <PopoverContent align="end" className="flex w-80 flex-col gap-3 p-3">
        <p className="text-xs font-medium text-fg">Extra options</p>
        {option(
          "Is nullable",
          "Specify if the column can assume a NULL value if no value is provided",
          c.nullable && !c.primaryKey,
          (v) => onChange({ nullable: v }),
          c.primaryKey,
        )}
        {option(
          "Is unique",
          "Enforce if values in the column should be unique across rows",
          c.unique,
          (v) => onChange({ unique: v }),
        )}
        {canIdentity(c) &&
          !c.original &&
          option(
            "Is Identity",
            "Automatically assign a sequential unique number to the column",
            c.identity,
            (v) => onChange({ identity: v }),
          )}
        {option(
          "Define as array",
          "Allow the column to be defined as variable-length multidimensional arrays",
          c.isArray,
          (v) => onChange({ isArray: v, identity: v ? false : c.identity }),
        )}
      </PopoverContent>
    </Popover>
  );
}

