/** Supabase's "Duplicate table": the same columns, constraints and indexes, optionally its rows. */
function DuplicateTableDialog({
  target,
  onClose,
}: {
  target: Target & { table: string };
  onClose: () => void;
}) {
  const { serverId, database, schema, table } = target;
  const [name, setName] = useState(`${table}_duplicate`);
  const [withRows, setWithRows] = useState(false);
  const copy = qualified(schema, name.trim());
  const source = qualified(schema, table);
  const valid = name.trim().length > 0 && name.trim() !== table;
  const sql = !valid
    ? "-- give the copy a new name"
    : [
        `CREATE TABLE ${copy} (LIKE ${source} INCLUDING ALL);`,
        ...(withRows
          ? [
              `INSERT INTO ${copy} OVERRIDING SYSTEM VALUE SELECT * FROM ${source};`,
              // Identity columns continue after the copied rows
              `DO $$ DECLARE r record; m bigint; BEGIN
  FOR r IN SELECT attname FROM pg_attribute WHERE attrelid = ${literal(copy)}::regclass AND attidentity <> '' LOOP
    EXECUTE format('SELECT max(%I) FROM %s', r.attname, ${literal(copy)}) INTO m;
    IF m IS NOT NULL THEN PERFORM setval(pg_get_serial_sequence(${literal(copy)}, r.attname), m); END IF;
  END LOOP;
END $$;`,
            ]
          : []),
      ].join("\n");
  return (
    <RunSqlDialog
      open
      onOpenChange={(o) => !o && onClose()}
      title={`Duplicate table ${table}`}
      description="Copies the columns, defaults, constraints and indexes. Foreign keys aren't copied."
      sql={sql}
      database={database}
      confirmLabel="Duplicate"
      successMessage={`Table ${name.trim()} created`}
      onDone={() =>
        useWorkspaceStore.getState().openTab(serverId, {
          type: "table",
          database,
          schema,
          name: name.trim(),
          kind: "table",
          view: "data",
        })
      }
    >
      <NameField value={name} onChange={setName} />
      <label className="flex cursor-pointer items-center gap-2 text-sm text-fg-muted">
        <Checkbox
          checked={withRows}
          onCheckedChange={(v) => setWithRows(v === true)}
        />
        Duplicate table entries
      </label>
    </RunSqlDialog>
  );
}
